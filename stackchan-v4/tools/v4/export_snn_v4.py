"""data/snn_v4.pt -> main/v4/snn_v4_data.h (int8 weights stored by presynaptic neuron, per-row float scales).

  ./py export_snn_v4.py            (no checkpoint: an untrained placeholder, kTrained = false)
"""
import os

import numpy as np
import torch

import snn_v4 as S
from spec_v4 import CHANNELS, SNN_OUT, ZONES

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CKPT = os.path.join(HERE, "data", "snn_v4.pt")
OUT = os.path.join(ROOT, "main", "v4", "snn_v4_data.h")


def quant_rows(w):
    s = np.maximum(np.abs(w).max(1, keepdims=True), 1e-8) / 127.0
    return np.clip(np.round(w / s), -127, 127).astype(np.int8), s[:, 0].astype(np.float32)


def cf(v):
    """A C++ float literal (0 -> 0.0f: "0f" is not one)."""
    t = f"{float(v):.9g}"
    return (t if ("." in t or "e" in t or "n" in t) else t + ".0") + "f"


def arr(name, a, ctype):
    flat = np.asarray(a).ravel()
    if ctype == "float":
        body = ", ".join(cf(v) for v in flat)
    else:
        body = ", ".join(str(int(v)) for v in flat)
    return f"inline constexpr {ctype} {name}[{len(flat)}] = {{{body}}};"


def main():
    model = S.SnnV4()
    trained = os.path.exists(CKPT)
    if trained:
        model.load_state_dict(torch.load(CKPT, weights_only=False, map_location="cpu")["state"])
    model.quant = False
    with torch.no_grad():
        w_in = model.W("in").numpy()
        w_rec = model.W("rec").numpy()
        w_att = model.W("att").numpy()
        w_ro = model.W("ro").numpy()
    q_in, s_in = quant_rows(w_in)
    q_rec, s_rec = quant_rows(w_rec)
    q_att, s_att = quant_rows(w_att)
    q_ro, s_ro = quant_rows(w_ro)
    wz = S.zone_weights().reshape(len(CHANNELS), len(ZONES), 4, len(CHANNELS), S.N_GRF)
    zone = np.stack([np.stack([wz[c, z, 0, c] for z in range(len(ZONES))]) for c in range(len(CHANNELS))])
    L = ["// GENERATED by tools/v4/export_snn_v4.py - do not edit.", "#pragma once", "#include <cstdint>", "",
         "namespace snnv4 {", f"inline constexpr bool kTrained = {'true' if trained else 'false'};",
         f"inline constexpr float kGrfGain = {S.GRF_GAIN}f, kGrfSigma = {S.GRF_SIGMA:.9g}f, "
         f"kOnOffGain = {S.ONOFF_GAIN}f;",
         f"inline constexpr float kBetaEnc = {S.BETA_ENC:.9g}f, kBetaZone = {S.BETA_ZONE:.9g}f, "
         f"kBetaMix = {S.BETA_MIX:.9g}f, kBetaAtt = {S.BETA_ATT:.9g}f;",
         f"inline constexpr float kBumpSx = {S.BUMP_SX}f, kBumpSy = {S.BUMP_SY}f, kBumpGain = {S.BUMP_GAIN}f;",
         "inline constexpr float kAdaptKeep[4] = {" +
         ", ".join(cf(np.exp(-S.DT_SUB / t)) for t in S.ZONE_ADAPT_TAU) + "};",
         "inline constexpr float kAdaptStep[4] = {" + ", ".join(cf(v) for v in S.ZONE_ADAPT_STEP) + "};",
         f"inline constexpr float kZoneW[{len(CHANNELS)}][{len(ZONES)}][{S.N_GRF}] = {{" +
         ", ".join("{" + ", ".join("{" + ", ".join(cf(v) for v in zone[c, z]) + "}"
                                   for z in range(len(ZONES))) + "}" for c in range(len(CHANNELS))) + "};",
         arr("kWInT", q_in.T, "int8_t"), arr("kInScale", s_in, "float"),
         arr("kWRecT", q_rec.T, "int8_t"), arr("kRecScale", s_rec, "float"),
         arr("kWAttT", q_att.T, "int8_t"), arr("kAttScale", s_att, "float"),
         arr("kWRoT", q_ro.T, "int8_t"), arr("kRoScale", s_ro, "float"),
         arr("kBMix", model.b_mix.detach().numpy(), "float"), arr("kBAtt", model.b_att.detach().numpy(), "float"),
         arr("kBRo", model.b_ro.detach().numpy(), "float"), arr("kRoKeep", model.ro_keep.numpy(), "float"),
         arr("kSigned", model.signed.numpy().astype(int), "uint8_t"),
         "}  // namespace snnv4", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    kb = (q_in.size + q_rec.size + q_att.size + q_ro.size) / 1024
    print(f"wrote {OUT}: trained={trained}, {kb:.0f} KB int8, outputs {len(SNN_OUT)}")


if __name__ == "__main__":
    main()

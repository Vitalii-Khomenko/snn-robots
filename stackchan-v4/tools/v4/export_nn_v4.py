"""data/nn_v4.pt -> main/v4/nn_v4_data.h (float weights; ~31 k parameters).

  ./py export_nn_v4.py            (no checkpoint: an untrained placeholder, kTrained = false)
"""
import os

import numpy as np
import torch

from nn_v4 import ACT_IDX, EMO_IDX, GROUPS, SIG, SIGNED, STRENGTH, NnV4

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
CKPT = os.path.join(HERE, "data", "nn_v4.pt")
OUT = os.path.join(ROOT, "main", "v4", "nn_v4_data.h")


def cf(v):
    """A C++ float literal (0 -> 0.0f: "0f" is not one)."""
    t = f"{float(v):.9g}"
    return (t if ("." in t or "e" in t or "n" in t) else t + ".0") + "f"


def arr(name, a, ctype="float"):
    flat = np.asarray(a).ravel()
    body = ", ".join(cf(v) for v in flat) if ctype == "float" else ", ".join(str(int(v)) for v in flat)
    return f"inline constexpr {ctype} {name}[{len(flat)}] = {{{body}}};"


def main():
    m = NnV4()
    trained = os.path.exists(CKPT)
    if trained:
        m.load_state_dict(torch.load(CKPT, weights_only=False, map_location="cpu")["state"])
    sd = {k: v.detach().numpy() for k, v in m.state_dict().items()}
    kind = np.zeros(len(EMO_IDX) + 1 + len(ACT_IDX), np.int32)  # per output: 0 sigmoid, 1 tanh, 2..6 softmax group
    for g, (name, idx) in enumerate(GROUPS.items()):
        kind[idx] = 3 + g
    kind[EMO_IDX] = 2
    kind[SIGNED] = 1
    L = ["// GENERATED by tools/v4/export_nn_v4.py - do not edit.", "#pragma once", "#include <cstdint>", "",
         "namespace nnv4 {", f"inline constexpr bool kTrained = {'true' if trained else 'false'};",
         arr("kWih", sd["gru.weight_ih_l0"]), arr("kWhh", sd["gru.weight_hh_l0"]),
         arr("kBih", sd["gru.bias_ih_l0"]), arr("kBhh", sd["gru.bias_hh_l0"]),
         arr("kWEmo", sd["emo.weight"]), arr("kBEmo", sd["emo.bias"]),
         arr("kWAct1", sd["act1.weight"]), arr("kBAct1", sd["act1.bias"]),
         arr("kWAct2", sd["act2.weight"]), arr("kBAct2", sd["act2.bias"]),
         arr("kEmoIdx", EMO_IDX, "uint8_t"), f"inline constexpr int kStrengthIdx = {STRENGTH};",
         arr("kActIdx", ACT_IDX, "uint8_t"), arr("kKind", kind, "uint8_t"),
         "}  // namespace nnv4", ""]
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    n = sum(v.size for v in sd.values())
    print(f"wrote {OUT}: trained={trained}, {n} parameters")


if __name__ == "__main__":
    main()

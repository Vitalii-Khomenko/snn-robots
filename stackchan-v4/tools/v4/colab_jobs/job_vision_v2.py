import os
import time
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

t0 = time.time()
dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("VisionNetV2 on", dev, torch.cuda.get_device_name(0) if torch.cuda.is_available() else "", flush=True)


class FakeQuant(torch.autograd.Function):
    @staticmethod
    def forward(ctx, w):
        flat = w.reshape(w.shape[0], -1)
        s = flat.abs().amax(dim=1).clamp_min(1e-8) / 127.0
        s = s.reshape(-1, *([1] * (w.dim() - 1)))
        return torch.round(w / s).clamp(-127, 127) * s

    @staticmethod
    def backward(ctx, g):
        return g


class VisionNetV2(nn.Module):
    """Exact nn::conv3x3Pool + nn::dense architecture (~23.8 KB int8, < 12 ms on ESP32-S3 Core 1)."""
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(3, 8, 3, padding=1)
        self.conv2 = nn.Conv2d(8, 16, 3, padding=1)
        self.conv3 = nn.Conv2d(16, 24, 3, padding=1)
        self.fc1 = nn.Linear(24 * 3 * 4 + 4, 64)
        self.fc2 = nn.Linear(64, 5)  # person, face, target_x, target_y, target_conf
        self.quant = False

    def qw(self, w):
        return FakeQuant.apply(w) if self.quant else w

    def forward(self, img, side):
        x = F.relu(F.conv2d(img, self.qw(self.conv1.weight), self.conv1.bias, padding=1))
        x = F.max_pool2d(x, 2)
        x = F.relu(F.conv2d(x, self.qw(self.conv2.weight), self.conv2.bias, padding=1))
        x = F.max_pool2d(x, 2)
        x = F.relu(F.conv2d(x, self.qw(self.conv3.weight), self.conv3.bias, padding=1))
        x = F.max_pool2d(x, 2).flatten(1)
        x = F.relu(F.linear(torch.cat([x, side], 1), self.qw(self.fc1.weight), self.fc1.bias))
        return F.linear(x, self.qw(self.fc2.weight), self.fc2.bias)


def quantize(w):
    w = w.detach().cpu().numpy().astype(np.float32)
    flat = w.reshape(w.shape[0], -1)
    s = np.maximum(np.abs(flat).max(axis=1), 1e-8) / 127.0
    q = np.clip(np.round(flat / s[:, None]), -127, 127).astype(np.int8)
    return q.reshape(w.shape), s.astype(np.float32)


def export_header(model, path):
    parts = []
    for name in ("conv1", "conv2", "conv3", "fc1", "fc2"):
        m = getattr(model, name)
        q, s = quantize(m.weight)
        b = m.bias.detach().cpu().numpy().astype(np.float32)
        parts.append(f"static const int8_t {name}_w[{q.size}] = {{" + ",".join(str(int(v)) for v in q.ravel()) + "};")
        parts.append(f"static const float {name}_s[{s.size}] = {{" + ",".join(f"{float(v):.8e}f" for v in s.ravel()) + "};")
        parts.append(f"static const float {name}_b[{b.size}] = {{" + ",".join(f"{float(v):.8e}f" for v in b.ravel()) + "};")
    with open(path, "w") as f:
        f.write("// GENERATED by tools/v4/colab_jobs/job_vision_v2.py (VisionNetV2 int8) - do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace vision_model {\n")
        f.write("static constexpr bool kTrained = true;\n")
        f.write("\n".join(parts))
        f.write("\n}  // namespace vision_model\n")


def augment(img, side, lab):
    B = img.shape[0]
    flip = torch.rand(B, device=img.device) < 0.5
    img = torch.where(flip[:, None, None, None], img.flip(3), img)
    side = side.clone()
    side[:, 0] = torch.where(flip, -side[:, 0], side[:, 0])
    lab = lab.clone()
    lab[:, 2] = torch.where(flip, -lab[:, 2], lab[:, 2])  # target_x mirrors
    gain = torch.empty(B, 1, 1, 1, device=img.device).uniform_(0.65, 1.45)
    img = img * gain
    dx = int(torch.randint(-2, 3, (1,)).item())
    dy = int(torch.randint(-1, 2, (1,)).item())
    img = torch.roll(img, (dy, dx), (2, 3))
    ramp = torch.linspace(-1, 1, 32, device=img.device)[None, None, None, :] * torch.empty(B, 1, 1, 1, device=img.device).uniform_(-0.3, 0.3)
    img = torch.cat([img[:, :1] + ramp * img[:, :1].abs().mean((1, 2, 3), keepdim=True), img[:, 1:]], 1)
    img = img + torch.randn_like(img) * torch.empty(B, 1, 1, 1, device=img.device).uniform_(0.0, 0.05)
    return img, side, lab


def loss_fn(logits, lab, src):
    # src: 3=room_media (weight 3.0), 2=real_rec (2.5), 1=coco (1.5), 0=synth (0.8)
    sw = torch.where(src == 3, 3.0, torch.where(src == 2, 2.5, torch.where(src == 1, 1.5, 0.8)))
    # BCE on person(0), face(1), target_conf(4)
    loss = 0.0
    for c, pw in ((0, 1.8), (1, 2.5), (4, 1.5)):
        y = lab[:, c]
        ok = ~torch.isnan(y)
        yt = torch.nan_to_num(y, 0.0).clamp(0.0, 1.0)
        bce = F.binary_cross_entropy_with_logits(logits[:, c], yt, reduction="none")
        w = ok.float() * sw * torch.where(yt > 0.5, pw, 1.0)
        loss = loss + (bce * w).sum() / w.sum().clamp_min(1.0)
    # MSE on target_x(2), target_y(3) where target_conf > 0.3
    conf = torch.nan_to_num(lab[:, 4], 0.0) > 0.3
    for c in (2, 3):
        y = lab[:, c]
        ok = (~torch.isnan(y)) & conf
        if ok.any():
            err = (torch.tanh(logits[:, c]) - torch.nan_to_num(y, 0.0)) ** 2
            w = ok.float() * sw
            loss = loss + 2.0 * (err * w).sum() / w.sum().clamp_min(1.0)
    return loss


@torch.no_grad()
def evaluate(model, im, sd, lb, src, bs=2048):
    model.eval()
    outs = []
    for i in range(0, len(im), bs):
        xi = torch.from_numpy(im[i:i + bs]).to(dev).float() / 60.0
        xs = torch.from_numpy(sd[i:i + bs].astype(np.float32)).to(dev)
        outs.append(model(xi, xs).cpu().numpy())
    O = np.concatenate(outs)
    P = np.empty_like(O)
    for c in (0, 1, 4):
        P[:, c] = 1.0 / (1.0 + np.exp(-np.clip(O[:, c], -20, 20)))
    for c in (2, 3):
        P[:, c] = np.tanh(O[:, c])
    rep = {}
    for label, m in (("room_day", src == 3), ("real_rec", src == 2), ("coco", src == 1), ("all", np.ones(len(src), bool))):
        if m.sum() == 0:
            continue
        sub = {}
        for c, name in ((0, "person"), (1, "face"), (4, "target_conf")):
            ok = np.isfinite(lb[m, c])
            if ok.sum() < 10:
                continue
            yt = lb[m, c][ok] > 0.5
            yp = P[m, c][ok] > 0.5
            tp = int((yt & yp).sum())
            fp = int((~yt & yp).sum())
            fn = int((yt & ~yp).sum())
            prec = tp / max(1, tp + fp)
            rec = tp / max(1, tp + fn)
            f1 = 2 * prec * rec / max(1e-6, prec + rec)
            sub[name] = (prec, rec, f1, int(yt.sum()))
        conf_ok = (np.nan_to_num(lb[m, 4], 0.0) > 0.3) & np.isfinite(lb[m, 2])
        if conf_ok.sum() >= 5:
            sub["tx_mae"] = float(np.abs(P[m, 2][conf_ok] - lb[m, 2][conf_ok]).mean())
            sub["ty_mae"] = float(np.abs(P[m, 3][conf_ok] - lb[m, 3][conf_ok]).mean())
        rep[label] = sub
    model.train()
    return rep


z = np.load("/content/vision_v2_data.npz")
im_tr, sd_tr, lb_tr, src_tr = z["im_tr"], z["sd_tr"].astype(np.float32), z["lb_tr"].astype(np.float32), z["src_tr"]
im_v, sd_v, lb_v, src_v = z["im_v"], z["sd_v"].astype(np.float32), z["lb_v"].astype(np.float32), z["src_v"]
print(f"Loaded train {im_tr.shape} val {im_v.shape}", flush=True)

model = VisionNetV2().to(dev)
opt = torch.optim.AdamW(model.parameters(), lr=2.5e-3, weight_decay=1e-4)
EPOCHS = 36
QAT_AT = 28
sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=EPOCHS)
BS = 512
rng = np.random.default_rng(0)
best_score = -1.0
best_state = None
lines = []

for ep in range(EPOCHS):
    model.quant = (ep >= QAT_AT)
    if ep == QAT_AT:
        for pg in opt.param_groups:
            pg["lr"] = 4e-4
    perm = rng.permutation(len(im_tr))
    tot, nb = 0.0, 0
    for i in range(0, len(perm), BS):
        idx = perm[i:i + BS]
        xi = torch.from_numpy(im_tr[idx]).to(dev).float() / 60.0
        xs = torch.from_numpy(sd_tr[idx]).to(dev)
        yl = torch.from_numpy(lb_tr[idx]).to(dev)
        sb = torch.from_numpy(src_tr[idx]).to(dev)
        xi, xs, yl = augment(xi, xs, yl)
        loss = loss_fn(model(xi, xs), yl, sb)
        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 2.0)
        opt.step()
        tot += float(loss)
        nb += 1
    sched.step()
    rep = evaluate(model, im_v, sd_v, lb_v, src_v)
    rm = rep.get("room_day", {})
    rr = rep.get("real_rec", {})
    p_f1 = rm.get("person", (0, 0, 0))[2]
    f_f1 = rm.get("face", (0, 0, 0))[2]
    rr_p = rr.get("person", (0, 0, 0))[2]
    score = 0.45 * p_f1 + 0.35 * f_f1 + 0.20 * rr_p
    msg = (f"ep {ep+1:02d}/{EPOCHS} {'Q ' if model.quant else '  '}loss {tot/nb:.4f} | "
           f"room person F1={p_f1:.3f} face F1={f_f1:.3f} tx_mae={rm.get('tx_mae', 0):.3f} | real_rec person F1={rr_p:.3f}")
    print(msg, flush=True)
    lines.append(msg)
    if model.quant and score > best_score:
        best_score = score
        best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

model.load_state_dict(best_state)
model.quant = True
rep = evaluate(model, im_v, sd_v, lb_v, src_v)
lines.append("\n=== FINAL HELD-OUT METRICS (INT8 QAT) ===")
for grp, sub in rep.items():
    lines.append(f"[{grp}]")
    for k, v in sub.items():
        if isinstance(v, tuple):
            lines.append(f"  {k:12s} prec={v[0]:.3f} rec={v[1]:.3f} f1={v[2]:.3f} (pos={v[3]})")
        else:
            lines.append(f"  {k:12s} {v:.3f}")

os.makedirs("/content/out", exist_ok=True)
torch.save({"state": best_state, "arch": "VisionNetV2", "score": best_score}, "/content/out/vision_v2.pt")
export_header(model, "/content/out/vision_model_data.h")
with open("/content/out/vision_v2_report.txt", "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines[-25:]), flush=True)
print(f"Done in {(time.time() - t0)/60:.1f} min", flush=True)

"""Colab T4 GPU job: train AuditoryNetV2 (2D Spectro-Temporal ConvNet + Context MLP, int8 QAT)
and export main/perception/auditory_model_data.h + report.
"""
import os
import time
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

t0 = time.time()
dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print("AuditoryNetV2 on", dev, torch.cuda.get_device_name(0) if torch.cuda.is_available() else "", flush=True)

AUDIO_OUT = ["silence", "speech", "clap", "sharp", "continuous", "low", "high", "tonal"]


class FakeQuant(torch.autograd.Function):
    @staticmethod
    def forward(ctx, w):
        flat = w.reshape(w.shape[0], -1)
        s = flat.abs().amax(dim=1).clamp_min(1e-8) / 127.0
        s = s.reshape(-1, *([1] * (w.dim() - 1)))
        return torch.round(w / s).clamp(-127, 127) * s

    @staticmethod
    def backward(ctx, g):
        return g


class AuditoryNetV2(nn.Module):
    """Input [B, 100] = 6x16 spectro-temporal grid + 4 context features.
    conv1(1->12, 3x3, pad 1) + ReLU + MaxPool2d(2) -> [12, 3, 8] = 288 + 4 side = 292 -> 64 -> 32 -> 8.
    Uses exact nn::conv3x3Pool and nn::dense kernels in main/perception/nn_ops.h (~21 KB int8, < 0.8 ms on ESP32-S3).
    """
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, 12, 3, padding=1)
        self.fc1 = nn.Linear(12 * 3 * 8 + 4, 64)
        self.fc2 = nn.Linear(64, 32)
        self.fc3 = nn.Linear(32, 8)
        self.quant = False

    def qw(self, w):
        return FakeQuant.apply(w) if self.quant else w

    def forward(self, x):
        spec = x[:, :96].reshape(-1, 1, 6, 16)
        side = x[:, 96:]
        h = F.relu(F.conv2d(spec, self.qw(self.conv1.weight), self.conv1.bias, padding=1))
        h = F.max_pool2d(h, 2).flatten(1)
        h = F.relu(F.linear(torch.cat([h, side], 1), self.qw(self.fc1.weight), self.fc1.bias))
        h = F.relu(F.linear(h, self.qw(self.fc2.weight), self.fc2.bias))
        return F.linear(h, self.qw(self.fc3.weight), self.fc3.bias)


def quantize(w):
    w = w.detach().cpu().numpy().astype(np.float32)
    flat = w.reshape(w.shape[0], -1)
    s = np.maximum(np.abs(flat).max(axis=1), 1e-8) / 127.0
    q = np.clip(np.round(flat / s[:, None]), -127, 127).astype(np.int8)
    return q.reshape(w.shape), s.astype(np.float32)


def export_header(model, path):
    parts = []
    for name in ("conv1", "fc1", "fc2", "fc3"):
        m = getattr(model, name)
        q, s = quantize(m.weight)
        b = m.bias.detach().cpu().numpy().astype(np.float32)
        parts.append(f"static const int8_t {name}_w[{q.size}] = {{" + ",".join(str(int(v)) for v in q.ravel()) + "};")
        parts.append(f"static const float {name}_s[{s.size}] = {{" + ",".join(f"{float(v):.8e}f" for v in s.ravel()) + "};")
        parts.append(f"static const float {name}_b[{b.size}] = {{" + ",".join(f"{float(v):.8e}f" for v in b.ravel()) + "};")
    with open(path, "w") as f:
        f.write("// GENERATED by tools/v4/colab_jobs/job_audio_v2.py (AuditoryNetV2 2D ConvNet) - do not edit.\n")
        f.write("#pragma once\n#include <cstdint>\n\nnamespace auditory_model {\n")
        f.write("static constexpr bool kTrained = true;\n")
        f.write("static constexpr int kConvChannels = 12;\n")
        f.write("\n".join(parts))
        f.write("\n}  // namespace auditory_model\n")


def augment(x):
    B = x.shape[0]
    x = x.clone()
    bands = x[:, :96].reshape(B, 6, 16)
    gain = torch.empty(B, 1, 1, device=x.device).uniform_(-0.08, 0.10)
    tilt = torch.empty(B, 1, 16, device=x.device).uniform_(-0.04, 0.04)
    bands = (bands + gain + tilt).clamp_min(0.0) + torch.randn_like(bands) * 0.012
    # Light frequency masking (SpecAugment) on 25% of batch
    if torch.rand(1).item() < 0.5:
        fb = int(torch.randint(0, 15, (1,)).item())
        mask = torch.rand(B, 1, 1, device=x.device) < 0.25
        bands[:, :, fb:fb + 2] = torch.where(mask, torch.zeros_like(bands[:, :, fb:fb + 2]), bands[:, :, fb:fb + 2])
    x[:, :96] = bands.reshape(B, 96)
    x[:, 97] = (x[:, 97] + gain[:, 0, 0]).clamp_min(0.0)
    flip = torch.rand(B, device=x.device) < 0.5
    x[:, 96] = torch.where(flip, -x[:, 96], x[:, 96])
    return x


def loss_fn(logits, y, src):
    ok = ~torch.isnan(y)
    yt = torch.nan_to_num(y, 0.0).clamp(0.0, 1.0)
    bce = F.binary_cross_entropy_with_logits(logits, yt, reduction="none")
    # Emphasize speech recall (3.5x on pos) & real_mic sessions (5x, since real_mic is ~10x smaller than room_media),
    # while still keeping strict false-positive suppression on clap(2)/sharp(3) (2.2x on neg).
    cls_w = torch.tensor([1.0, 2.0, 1.6, 1.6, 1.0, 1.0, 1.0, 1.0], device=y.device)[None, :]
    pos_mul = torch.tensor([1.5, 3.5, 2.5, 2.5, 1.5, 2.0, 2.0, 2.0], device=y.device)[None, :]
    neg_mul = torch.tensor([1.0, 1.0, 2.2, 2.2, 1.0, 1.0, 1.0, 1.0], device=y.device)[None, :]
    pos_w = torch.where(yt > 0.5, pos_mul, neg_mul)
    src_w = torch.where(src == 1, 5.0, torch.where(src == 2, 1.5, 1.0))[:, None]
    w = ok.float() * cls_w * pos_w * src_w
    return (bce * w).sum() / w.sum().clamp_min(1.0)


@torch.no_grad()
def evaluate(model, X, Y, src, bs=4096):
    model.eval()
    preds = []
    for i in range(0, len(X), bs):
        xb = torch.from_numpy(X[i:i + bs].astype(np.float32)).to(dev)
        preds.append(torch.sigmoid(model(xb)).cpu().numpy())
    P = np.concatenate(preds)
    rep = {}
    for label, m in (("all", np.ones(len(src), bool)), ("room_media", src == 2), ("real_mic", src == 1)):
        if m.sum() == 0:
            continue
        sub = {}
        for c, name in enumerate(AUDIO_OUT):
            yc = Y[m, c]
            ok = np.isfinite(yc)
            if ok.sum() < 20:
                continue
            yt = yc[ok] > 0.5
            yp = P[m, c][ok] > 0.5
            tp = int((yt & yp).sum())
            fp = int((~yt & yp).sum())
            fn = int((yt & ~yp).sum())
            prec = tp / max(1, tp + fp)
            rec = tp / max(1, tp + fn)
            f1 = 2 * prec * rec / max(1e-6, prec + rec)
            sub[name] = (prec, rec, f1, int(yt.sum()), fp)
        rep[label] = sub
    model.train()
    return rep


z = np.load("/content/audio_v2_data.npz")
X_tr, Y_tr, src_tr = z["X_tr"].astype(np.float32), z["Y_tr"].astype(np.float32), z["src_tr"]
X_val, Y_val, src_val = z["X_val"].astype(np.float32), z["Y_val"].astype(np.float32), z["src_val"]
print(f"Loaded train {X_tr.shape} val {X_val.shape}", flush=True)

model = AuditoryNetV2().to(dev)
opt = torch.optim.AdamW(model.parameters(), lr=2.5e-3, weight_decay=1e-4)
EPOCHS = 32
QAT_AT = 24
sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=EPOCHS)
BS = 1024
rng = np.random.default_rng(0)
best_score = -1.0
best_state = None
lines = []

for ep in range(EPOCHS):
    model.quant = (ep >= QAT_AT)
    if ep == QAT_AT:
        for pg in opt.param_groups:
            pg["lr"] = 4e-4
    perm = rng.permutation(len(X_tr))
    tot, nb = 0.0, 0
    for i in range(0, len(perm), BS):
        idx = perm[i:i + BS]
        xb = augment(torch.from_numpy(X_tr[idx]).to(dev))
        yb = torch.from_numpy(Y_tr[idx]).to(dev)
        sb = torch.from_numpy(src_tr[idx]).to(dev)
        loss = loss_fn(model(xb), yb, sb)
        opt.zero_grad()
        loss.backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), 2.0)
        opt.step()
        tot += float(loss)
        nb += 1
    sched.step()
    rep = evaluate(model, X_val, Y_val, src_val)
    rm = rep.get("room_media", {})
    rc = rep.get("real_mic", {})
    al = rep.get("all", {})
    f1_sp_real = rc.get("speech", (0, 0, 0))[2]
    f1_sp_all = al.get("speech", (0, 0, 0))[2]
    f1_cl = rc.get("clap", (0, 0, 0))[2]
    f1_sh = rc.get("sharp", (0, 0, 0))[2]
    fp_cl_room = rm.get("clap", (0, 0, 0, 0, 0))[4]
    score = 0.40 * f1_sp_real + 0.25 * f1_sp_all + 0.175 * f1_cl + 0.175 * f1_sh
    msg = (f"ep {ep+1:02d}/{EPOCHS} {'Q ' if model.quant else '  '}loss {tot/nb:.4f} | "
           f"real_sp F1={f1_sp_real:.3f} all_sp={f1_sp_all:.3f} | real_clap F1={f1_cl:.3f} (room_fp={fp_cl_room}) | real_sharp F1={f1_sh:.3f}")
    print(msg, flush=True)
    lines.append(msg)
    if model.quant and score > best_score:
        best_score = score
        best_state = {k: v.cpu().clone() for k, v in model.state_dict().items()}

model.load_state_dict(best_state)
model.quant = True
rep = evaluate(model, X_val, Y_val, src_val)
lines.append("\n=== FINAL HELD-OUT METRICS (INT8 QAT) ===")
for grp, sub in rep.items():
    lines.append(f"[{grp}]")
    for name, (prec, rec, f1, pos, fp) in sub.items():
        lines.append(f"  {name:12s} prec={prec:.3f} rec={rec:.3f} f1={f1:.3f} (pos={pos}, fp={fp})")

os.makedirs("/content/out", exist_ok=True)
torch.save({"state": best_state, "arch": "AuditoryNetV2", "score": best_score}, "/content/out/auditory_v2.pt")
export_header(model, "/content/out/auditory_model_data.h")
with open("/content/out/audio_v2_report.txt", "w") as f:
    f.write("\n".join(lines) + "\n")
print("\n".join(lines[-25:]), flush=True)
print(f"Done in {(time.time() - t0)/60:.1f} min", flush=True)

"""Single source of truth for the hybrid brain's interfaces.

`python3 spec.py` regenerates main/hybrid/hybrid_spec.h (the C++ side).
Every vector below is a section of the FeatureBus; the order is the wire order
between the firmware, the simulator dumps and the training code.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

# What the Vision NN reports (one camera frame, ~7 per second).
VISION = ["motion_l", "motion_c", "motion_r", "motion_up", "motion_down", "person", "face", "loom", "recede",
          "brightness", "light_change", "target_x", "target_y", "target_conf", "activity", "light_x", "light_y",
          "light_strength"]
# What the Auditory NN reports (one value set per brain tick).
# (No sound direction: two microphones 5 cm apart cannot tell it - docs/HARDWARE.md.)
AUDIO = ["silence", "speech", "clap", "sharp", "continuous", "low", "high", "tonal", "approach",
         "energy", "novelty", "self_voice", "own_motion", "onset", "loud"]
# Body, touch, IMU, battery (deterministic encoders, no network).
BODY = ["yaw", "pitch", "yaw_vel", "pitch_vel", "real_yaw_vel", "real_pitch_vel", "imu_pitch", "imu_roll",
        "touch_head", "touch_screen", "shake", "tilt", "battery", "stamina", "light_delta", "speaker"]
# Time of day and the owner.
CTX = ["night", "day", "dawn", "dusk", "owner_near", "hour_sin", "hour_cos", "owner_arrived"]
# Prediction error: expectation (efference copy) versus what really happened.
PE = ["pe_motor", "pe_vision"]
# Efference copy: what the brain asked the body to do (read before it happens).
EFF = ["eff_yaw", "eff_pitch", "eff_sound"]
# Endogenous activity: slow random drifts the brain keeps generating in
# silence (Ornstein-Uhlenbeck pacemakers). They make attention wander and
# behaviour vary, and - being inputs - stay visible to the policy and to the
# training data (a random choice the policy cannot see cannot be learned).
NOISE = ["wander_x", "wander_y", "wander_slow", "jitter"]
# What the spiking core reports to the policy.
SNN = ["curiosity", "boredom", "arousal", "annoyance", "social", "playful", "fatigue", "sleep", "music", "alert",
       "att_x", "att_y", "att_strength", "nov_vis", "nov_aud", "nov_touch", "tr_touch", "tr_sound", "tr_person",
       "tr_motion", "tr_novelty", "tr_reward", "hab_touch", "hab_sound", "surprise"]
# The policy's previous output, fed back (a subset of ACTION).
PREV = ["prev_yaw", "prev_pitch", "prev_speed", "prev_sound", "prev_hold", "prev_explore", "prev_valence",
        "prev_arousal"]
# What the policy decides, all normalized.
ACTION = ["yaw", "pitch", "speed", "vigor", "gaze_x", "gaze_y", "sound_act", "sound_arousal", "sound_valence",
          "blink", "led_activity", "led_r", "led_g", "led_b", "hold", "explore", "voice_register", "voice_slope", "voice_expr", "voice_length",
          "voice_rate", "style_calm", "style_ask", "style_play", "style_grumble", "face_valence", "face_arousal", "lids",
          "invite", "startle",
          # which face to show (one-hot, the order of face_style.h's Emotion enum; the strongest wins)
          "emo_normal", "emo_happy", "emo_very_happy", "emo_laughing", "emo_sad", "emo_crying", "emo_sleepy", "emo_surprised",
          "emo_angry", "emo_annoyed", "emo_love", "emo_shy", "emo_wink", "emo_curious", "emo_confused", "emo_thinking",
          "emo_bored", "emo_scared", "emo_dizzy", "emo_cool", "emo_sick"]
# ACTION entries that are signed (tanh); the rest are 0..1 (sigmoid).
ACTION_SIGNED = {"yaw", "pitch", "gaze_x", "gaze_y", "sound_valence", "voice_slope", "face_valence"}

SNN_INPUT = VISION + AUDIO + BODY + CTX + PE + EFF + NOISE
# Slow needs, kept by deterministic C++ "body clocks" (HybridBrain::updateSlow): the spiking core cannot count minutes of silence
# (its slow drives stayed at 0.3-0.5 whatever happened), so boredom and social need are also kept exactly, and only the policy reads them.
SLOW = ["slow_boredom", "slow_social"]
# What the robot has learned on its own (hybrid/assoc_memory.h): plastic synapses from situation cues to two outcome
# populations, learned while it lives (not on the PC). Expectation of being petted / of being handled roughly.
LEARN = ["expect_reward", "expect_threat"]
POLICY_INPUT = VISION + AUDIO + BODY + CTX + PE + NOISE + SNN + PREV + SLOW + LEARN

GROUPS = [("Vision", "VIS", VISION), ("Audio", "AUD", AUDIO), ("Body", "BODY", BODY), ("Ctx", "CTX", CTX),
          ("Pe", "PE", PE), ("Eff", "EFF", EFF), ("Noise", "NOISE", NOISE), ("Snn", "SNN", SNN), ("Prev", "PREV", PREV), ("Slow", "SLOW", SLOW),
          ("Learn", "LEARN", LEARN),
          ("Action", "ACT", ACTION)]


def header():
    out = ["// GENERATED by tools/hybrid/spec.py - do not edit.", "#pragma once", "#include <cstdint>", "",
           "namespace hybrid {"]
    for title, tag, names in GROUPS:
        out.append(f"enum {title} : uint8_t {{")
        prefix = tag.lower() + "_"
        for n in names:
            out.append(f"    {tag}_{(n[len(prefix):] if n.startswith(prefix) else n).upper()},")
        out.append(f"    {tag}_COUNT")
        out.append("};")
        out.append(f"inline constexpr const char* k{title}Names[] = {{" +
                   ", ".join(f'"{n}"' for n in names) + "};")
    out.append("")
    out.append(f"inline constexpr int kSnnInputs = {len(SNN_INPUT)};")
    out.append(f"inline constexpr int kPolicyInputs = {len(POLICY_INPUT)};")
    # wire offsets of each group inside the two concatenations
    titles = {id(g): (t, tag) for t, tag, g in GROUPS}
    for label, order in (("Snn", [VISION, AUDIO, BODY, CTX, PE, EFF, NOISE]),
                         ("Pol", [VISION, AUDIO, BODY, CTX, PE, NOISE, SNN, PREV, SLOW, LEARN])):
        o = 0
        for g in order:
            out.append(f"inline constexpr int k{label}{titles[id(g)][0]}At = {o};")
            o += len(g)
    out.append("}  // namespace hybrid")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    path = os.path.join(ROOT, "main", "hybrid", "hybrid_spec.h")
    with open(path, "w") as f:
        f.write(header())
    print(f"wrote {path}: SNN input {len(SNN_INPUT)}, policy input {len(POLICY_INPUT)}, action {len(ACTION)}")


def col(group_list, name):
    """Index of `name` inside the concatenation of the groups in `group_list`."""
    o = 0
    for g in group_list:
        if name in g:
            return o + g.index(name)
        o += len(g)
    raise KeyError(name)


SNN_IN = [VISION, AUDIO, BODY, CTX, PE, EFF, NOISE]
POL_IN = [VISION, AUDIO, BODY, CTX, PE, NOISE, SNN, PREV, SLOW, LEARN]


def sin(name):
    return col(SNN_IN, name)


def pin(name):
    return col(POL_IN, name)

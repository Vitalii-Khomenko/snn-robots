"""Shared PyTorch helpers: INT8 quantization identical to main/hybrid/nn_ops.h
and a C++ header exporter."""
import numpy as np
import torch


class FakeQuant(torch.autograd.Function):
    """Symmetric INT8 per output row/channel, straight-through gradient."""

    @staticmethod
    def forward(ctx, w):
        flat = w.reshape(w.shape[0], -1)
        s = flat.abs().amax(dim=1).clamp_min(1e-8) / 127.0
        s = s.reshape(-1, *([1] * (w.dim() - 1)))
        return torch.round(w / s).clamp(-127, 127) * s

    @staticmethod
    def backward(ctx, g):
        return g


def quantize(w):
    """numpy/torch weight [rows, ...] -> (int8 array, float32 scale per row)."""
    w = np.asarray(w.detach().cpu() if hasattr(w, "detach") else w, dtype=np.float32)
    flat = w.reshape(w.shape[0], -1)
    s = np.maximum(np.abs(flat).max(axis=1), 1e-8) / 127.0
    q = np.clip(np.round(flat / s[:, None]), -127, 127).astype(np.int8)
    return q.reshape(w.shape), s.astype(np.float32)


class Header:
    """Collects arrays and writes one C++ header with `static const` tables."""

    def __init__(self, namespace, trained):
        self.ns, self.trained, self.parts = namespace, trained, []

    def int8(self, name, q):
        flat = np.asarray(q, np.int8).reshape(-1)
        self.parts.append(f"static const int8_t {name}[{flat.size}] = {{" + ",".join(str(int(v)) for v in flat) + "};")

    def u16(self, name, a):
        flat = np.asarray(a, np.uint16).reshape(-1)
        self.parts.append(f"static const uint16_t {name}[{max(flat.size, 1)}] = {{" + (",".join(str(int(v)) for v in flat) or "0") + "};")

    def u32(self, name, a):
        flat = np.asarray(a, np.uint32).reshape(-1)
        self.parts.append(f"static const uint32_t {name}[{max(flat.size, 1)}] = {{" + (",".join(str(int(v)) for v in flat) or "0") + "};")

    def float(self, name, a):
        flat = np.asarray(a, np.float32).reshape(-1)
        self.parts.append(f"static const float {name}[{flat.size}] = {{" +
                          ",".join(f"{float(v):.8e}f" for v in flat) + "};")

    def layer(self, name, weight, bias):
        q, s = quantize(weight)
        self.int8(name + "_w", q)
        self.float(name + "_s", s)
        self.float(name + "_b", bias.detach().cpu().numpy() if hasattr(bias, "detach") else bias)

    def const(self, name, value):
        self.parts.append(f"static constexpr {'bool' if isinstance(value, bool) else 'float' if isinstance(value, float) else 'int'} {name} = "
                          f"{str(value).lower() if isinstance(value, bool) else value};")

    def write(self, path, comment=""):
        with open(path, "w") as f:
            f.write(f"// GENERATED by tools/hybrid - do not edit. {comment}\n#pragma once\n#include <cstdint>\n\n")
            f.write(f"namespace {self.ns} {{\nstatic constexpr bool kTrained = {'true' if self.trained else 'false'};\n")
            f.write("\n".join(self.parts))
            f.write(f"\n}}  // namespace {self.ns}\n")
